def iter_children(topic):
    children = topic.get("children") or {}
    attached = children.get("attached")
    if isinstance(attached, list):
        for child in attached:
            if isinstance(child, dict):
                yield child


def clean_title(title: str) -> str:
    if not title:
        return title

    if re.fullmatch(r"[ABC]\d{3}", title):
        return ""
    if re.fullmatch(r"【?[ABC]\d+[^\]]*】?", title):
        return ""
    if re.fullmatch(r"\d+天-\d+时", title):
        parts = title.split("-")
        hour = int(parts[1].replace("时", ""))
        if hour < 10:
            title = "清早"
        elif hour < 12:
            title = "上午"
        elif hour < 14:
            title = "中午"
        elif hour < 18:
            title = "下午"
        else:
            title = "晚上"
    if title.startswith("任务名称："):
        title = title[len("任务名称：") :]
    if title.startswith("任务描述："):
        title = title[len("任务描述：") :]
    if title.startswith("游戏场景："):
        return ""
    if title.startswith("会去的地方："):
        return ""

    title = TITLE_REPLACEMENTS.get(title, title)
    title = re.sub(r"^【[^】]*尾声[^】]*】$", "", title)
    title = re.sub(r"^【[^】]*过渡[^】]*】$", "", title)
    title = title.replace(" / ", "\n")
    title = title.replace("→ ", "")
    title = title.replace("→", "")

    lines = []
    for raw_line in title.splitlines():
        line = raw_line.strip()
        if not line:
            continue
        if any(token in line for token in META_SUBSTRINGS):
            continue
        if line in {"（最淡。一个字的欢迎。实验观察者态度。）", "（停顿）"}:
            continue
        if line.startswith("进入【") and line.endswith("】"):
            continue
        lines.append(line)

    if not lines:
        return ""

    if len(lines) > 4:
        lines = lines[:4]

    return "\n".join(lines)


def should_delete(title: str) -> bool:
    if not title:
        return False
    for pattern in DELETE_PATTERNS:
        if pattern.match(title):
            return True
    return False


def rewrite_topic(topic):
    title = topic.get("title")
    if isinstance(title, str):
        title = clean_title(title)
        topic["title"] = title

    children = topic.get("children") or {}
    attached = children.get("attached")
    if not isinstance(attached, list):
        return

    new_children = []
    for child in attached:
        if not isinstance(child, dict):
            continue
        child_title = child.get("title") or ""
        if should_delete(child_title):
            continue
        rewrite_topic(child)
        if child.get("title"):
            new_children.append(child)
    children["attached"] = new_children
    topic["children"] = children


