def walk(topic: dict) -> int:
    changed = 0
    title = topic.get("title")
    if isinstance(title, str) and title in REPLACEMENTS:
        topic["title"] = REPLACEMENTS[title]
        changed += 1

    for child in ((topic.get("children") or {}).get("attached") or []):
        if isinstance(child, dict):
            changed += walk(child)
    return changed


def main() -> None:
    with zipfile.ZipFile(XMIND_PATH, "r") as zin:
        data = json.loads(zin.read("content.json").decode("utf-8"))
        other_entries = {
            info.filename: zin.read(info.filename)
            for info in zin.infolist()
            if info.filename != "content.json"
        }

    changed = 0
    for sheet in data:
        root = sheet.get("rootTopic") or {}
        changed += walk(root)

    tmp = XMIND_PATH.with_suffix(".tmp")
    with zipfile.ZipFile(tmp, "w", zipfile.ZIP_DEFLATED) as zout:
        zout.writestr("content.json", json.dumps(data, ensure_ascii=False).encode("utf-8"))
        for name, payload in other_entries.items():
            zout.writestr(name, payload)

    shutil.move(tmp, XMIND_PATH)
    print(f"patched {changed} nodes in {XMIND_PATH}")


if __name__ == "__main__":
    main()
